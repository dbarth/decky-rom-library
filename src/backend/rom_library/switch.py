"""Facts from a Nintendo Switch NSP or XCI: the title, publisher, version, languages and age ratings
of the control NCA's NACP. The NCAs are encrypted: the keys come from the user's emulator."""
import os
import re
import struct

from . import aes

# Where Switch emulators keep prod.keys and title.keys, first found first.
KEY_DIRS = (
    "~/.local/share/eden/keys",
    "~/.local/share/citron/keys",
    "~/.local/share/sudachi/keys",
    "~/.local/share/suyu/keys",
    "~/.local/share/yuzu/keys",
    "~/.config/Ryujinx/system",
    "~/.var/app/io.github.ryubing.Ryujinx/config/Ryujinx/system",
    "~/.var/app/org.ryujinx.Ryujinx/config/Ryujinx/system",
    "~/.var/app/org.yuzu_emu.yuzu/data/yuzu/keys",
    "~/.switch",
)
CONTROL = 2
# The NACP's 16 titles and its supported-language bits, in their order.
LANGUAGES = (
    "American English", "British English", "Japanese", "French", "German", "Latin American Spanish",
    "Spanish", "Italian", "Dutch", "Canadian French", "Portuguese", "Russian", "Korean",
    "Traditional Chinese", "Simplified Chinese", "Brazilian Portuguese",
)
# The rating boards of the NACP's age table, in its order.
BOARDS = ("CERO", "GRAC", "GSRMR", "ESRB", "ClassInd", "USK", "PEGI", "PEGI Portugal", "PEGI BBFC", "Russian",
          "ACB", "OFLC", "IARC")
KEY_LINE = re.compile(r"^\s*(\w+)\s*=\s*([0-9a-fA-F]+)\s*$")


class Unreadable(Exception):
    pass


def read_keys(path):
    keys = {}
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = KEY_LINE.match(line)
                if m:
                    keys[m.group(1).lower()] = bytes.fromhex(m.group(2))
    except (OSError, ValueError):
        pass
    return keys


def find_keys(home):
    """Return (prod keys, title keys by rights id) from the first emulator folder that has prod.keys."""
    for d in KEY_DIRS:
        folder = home + d[1:]
        prod = read_keys(os.path.join(folder, "prod.keys"))
        if prod.get("header_key"):
            titles = {}
            for name in ("title.keys", "title.keys_autogenerated"):
                titles.update(read_keys(os.path.join(folder, name)))
            return prod, titles
    return None, {}


def partitions(f, offset=0, magic=b"PFS0"):
    """Return {name: (offset, size)} for a PFS0 or HFS0 partition at offset."""
    f.seek(offset)
    head = f.read(16)
    if head[:4] != magic:
        raise Unreadable(f"no {magic.decode()} at {offset:#x}")
    count, names_size = struct.unpack("<II", head[4:12])
    entry_size = 0x18 if magic == b"PFS0" else 0x40
    if count > 10000:
        raise Unreadable("too many entries")
    entries = f.read(count * entry_size)
    names = f.read(names_size)
    data = offset + 16 + count * entry_size + names_size
    out = {}
    for i in range(count):
        at, size, name_at = struct.unpack("<QQI", entries[i * entry_size:i * entry_size + 20])
        name = names[name_at:names.index(b"\0", name_at)].decode("utf-8", "replace")
        out[name] = (data + at, size)
    return out


def contents(f):
    """Return {name: (offset, size)} for the files of an NSP, or of an XCI's secure partition."""
    f.seek(0x100)
    if f.read(4) == b"HEAD":
        f.seek(0x130)
        root = struct.unpack("<Q", f.read(8))[0]
        secure = partitions(f, root, b"HFS0").get("secure")
        if not secure:
            raise Unreadable("the XCI has no secure partition")
        return partitions(f, secure[0], b"HFS0")
    return partitions(f)


class Nca:
    def __init__(self, f, offset, keys, title_key):
        self.f = f
        self.offset = offset
        f.seek(offset)
        raw = f.read(0xC00)
        if len(raw) < 0xC00:
            raise Unreadable("short NCA")
        self.header = aes.xts(keys["header_key"], raw, 0)
        h = self.header
        if h[0x200:0x204] != b"NCA3":
            raise Unreadable("not an NCA3, or the wrong header_key")
        self.content_type = h[0x205]
        self.title_id = struct.unpack("<Q", h[0x210:0x218])[0]
        revision = max(h[0x206], h[0x220])
        revision = revision - 1 if revision else 0
        rights = h[0x230:0x240]
        if any(rights):
            if title_key is None:
                raise Unreadable("no title key for the rights id " + rights.hex())
            kek = keys.get(f"titlekek_{revision:02x}")
            if not kek:
                raise Unreadable(f"prod.keys lacks titlekek_{revision:02x}")
            self.key = aes.ecb(kek, title_key)
        else:
            kind = ("application", "ocean", "system")[h[0x207]]
            kak = keys.get(f"key_area_key_{kind}_{revision:02x}")
            if not kak:
                raise Unreadable(f"prod.keys lacks key_area_key_{kind}_{revision:02x}")
            self.key = aes.ecb(kak, h[0x300:0x340])[0x20:0x30]

    def section(self, index):
        """Return (start, end, fs header) of a section, offsets relative to the NCA."""
        start, end = struct.unpack("<II", self.header[0x240 + index * 0x10:0x248 + index * 0x10])
        return start * 0x200, end * 0x200, self.header[0x400 + index * 0x200:0x600 + index * 0x200]

    def read(self, fs, offset, size):
        """Read and decrypt size bytes at offset in the NCA, inside a CTR section."""
        if fs[4] not in (3, 5):
            raise Unreadable(f"section encryption {fs[4]}")
        start = offset & ~0xF
        self.f.seek(self.offset + start)
        data = self.f.read(offset + size - start)
        counter = bytes(reversed(fs[0x140:0x148])) + (start >> 4).to_bytes(8, "big")
        return aes.ctr(self.key, counter, data)[offset - start:]

    def romfs_files(self):
        """Return {name: bytes reader} for the files of section 0's RomFS."""
        start, _, fs = self.section(0)
        if fs[2] != 0 or fs[3] != 3 or fs[8:12] != b"IVFC":
            raise Unreadable("section 0 is no RomFS")
        # The last of the six integrity levels holds the RomFS itself.
        level, _ = struct.unpack("<QQ", fs[8 + 0x10 + 0x18 * 5:8 + 0x20 + 0x18 * 5])
        base = start + level
        head = struct.unpack("<10Q", self.read(fs, base, 0x50))
        meta_at, meta_size, data_at = head[7], head[8], head[9]
        meta = self.read(fs, base + meta_at, meta_size)
        out, i = {}, 0
        while i + 0x20 <= len(meta):
            at, size = struct.unpack("<QQ", meta[i + 8:i + 24])
            name_size = struct.unpack("<I", meta[i + 0x1C:i + 0x20])[0]
            name = meta[i + 0x20:i + 0x20 + name_size].decode("utf-8", "replace")
            out[name] = (lambda at=at, size=size: self.read(fs, base + data_at + at, size))
            i += 0x20 + (name_size + 3) // 4 * 4
        return out


def text(raw):
    return raw.split(b"\0", 1)[0].decode("utf-8", "replace").strip()


def parse_nacp(nacp):
    """Return the facts of a NACP: title, publisher, version, languages and ages."""
    titles = {}
    for i, language in enumerate(LANGUAGES):
        name = text(nacp[i * 0x300:i * 0x300 + 0x200])
        if name:
            titles[language] = (name, text(nacp[i * 0x300 + 0x200:(i + 1) * 0x300]))
    # Prefer the European titles, then the American ones.
    pick = next((titles[k] for k in ("British English", "American English", "French") if k in titles), None)
    pick = pick or next(iter(titles.values()), ("", ""))
    flags = struct.unpack("<I", nacp[0x302C:0x3030])[0]
    languages = [name for i, name in enumerate(LANGUAGES) if flags & (1 << i)]
    ages = {board: nacp[0x3040 + i] for i, board in enumerate(BOARDS) if nacp[0x3040 + i] != 0xFF}
    out = {
        "title": pick[0],
        "publisher": pick[1],
        "version": text(nacp[0x3060:0x3070]),
        "languages": languages,
        "ages": ages,
    }
    return {k: v for k, v in out.items() if v}


def read(path, home, keys=None):
    """Return the facts of an NSP or XCI, and its title id as serial."""
    prod, titles = keys or find_keys(home)
    if not prod:
        raise Unreadable("no prod.keys in an emulator's folder")
    with open(path, "rb") as f:
        files = contents(f)
        tickets = {}
        for name, (at, size) in files.items():
            if name.endswith(".tik") and size >= 0x2C0:
                f.seek(at)
                tik = f.read(0x2C0)
                tickets[tik[0x2A0:0x2B0]] = tik[0x180:0x190]
        for name, (at, size) in files.items():
            if not name.endswith(".nca") or name.endswith(".cnmt.nca") or size > 64 << 20:
                continue
            header = aes.xts(prod["header_key"], read_at(f, at, 0xC00), 0)
            if header[0x200:0x204] != b"NCA3" or header[0x205] != CONTROL:
                continue
            rights = header[0x230:0x240]
            title_key = tickets.get(rights) or titles.get(rights.hex())
            nca = Nca(f, at, prod, title_key)
            romfs = nca.romfs_files()
            if "control.nacp" not in romfs:
                continue
            facts = parse_nacp(romfs["control.nacp"]())
            facts["serial"] = f"{nca.title_id:016X}"
            return facts
    raise Unreadable("no control NCA")


def read_at(f, offset, size):
    f.seek(offset)
    return f.read(size)
